export interface TravelConversationItem {
  id: string;
  title: string;
  status: string;
  desc: string;
}

export interface TravelTheme {
  key: string;
  stageKey: string;
  icon: string;
  badge: string;
  title: string;
  desc: string;
  bg: string;
  border: string;
  emojis: string;
  conversations: TravelConversationItem[];
}

function make15(
  prefix: string,
  items: Array<[string, string, string]>,
): TravelConversationItem[] {
  return items.map(([title, status, desc], i) => ({
    id: `${prefix}_${i + 1}`,
    title,
    status,
    desc,
  }));
}

